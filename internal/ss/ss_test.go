func TestSpecVectors(t *testing.T) {
	for _, v := range vectors(t) {
		t.Run(v.Method, func(t *testing.T) {
			// Literal request/response fixtures come from tools/vectors (separate module,
			// standard HKDF + independent zeebo BLAKE3); never regenerated by package ss.
			s := server(t, v.Method)
			s.key = mustHex(t, v.Key)
			tr := &memTransport{input: bytes.NewReader(mustHex(t, v.TCPRequest))}
			c, e := s.Accept(tr)
			if e != nil {
				t.Fatal(e)
			}
			if c.Target() != testTarget || c.UserID() != "alice" {
				t.Fatal(c.Target(), c.UserID())
			}
			got, e := io.ReadAll(c)
			if e != nil || string(got) != "request payload" {
				t.Fatalf("payload %q %v", got, e)
			}
			s.random = bytes.NewReader(mustHex(t, v.ResponseSalt))
			if _, e = c.Write([]byte("response payload")); e != nil {
				t.Fatal(e)
			}
			if !bytes.Equal(tr.output.Bytes(), mustHex(t, v.TCPResponse)) {
				t.Fatalf("TCP response mismatch\n%x\n%s", tr.output.Bytes(), v.TCPResponse)
			}
			if tr.writes != 1 {
				t.Fatal("header/payload must be combined", tr.writes)
			}
			copySalt := c.RequestSalt()
			copySalt[0] ^= 0xff
			if bytes.Equal(copySalt, c.RequestSalt()) {
				t.Fatal("salt alias")
			}
			u := server(t, v.Method)
			if u.m.v2022 {
				u.random = bytes.NewReader(append(mustHex(t, "1112131415161718"), seq(0xa0, 24)...))
			} else {
				u.random = bytes.NewReader(mustHex(t, v.ResponseSalt))
			}
			p, e := u.DecodeUDP(mustHex(t, v.UDPRequest), testPeer)
			if e != nil {
				t.Fatal(e)
			}
			if p.Target != testTarget || string(p.Payload) != "request payload" || p.UserID != "alice" {
				t.Fatal(p)
			}
			wire, peer, e := u.EncodeUDP(p, testTarget, []byte("response payload"))
			if e != nil {
				t.Fatal(e)
			}
			if peer != testPeer || !bytes.Equal(wire, mustHex(t, v.UDPResponse)) {
				t.Fatalf("UDP response mismatch\n%x\n%s (%v)", wire, v.UDPResponse, peer)
			}
		})
	}
}

// The following construction helpers are only for malformed/state/size tests.
// They are NOT the source of fixed vectors or independent interop evidence.
func tcpRequest(t *testing.T, s *Server, salt []byte, stamp uint64, target Address, padding int, initial, tail []byte) []byte {
	t.Helper()
	a, e := s.aead(salt)
	if e != nil {
		t.Fatal(e)
	}
	var n counter
	address, e := target.MarshalBinary()
	if e != nil {
		t.Fatal(e)
	}
	wire := append([]byte(nil), salt...)
	add := func(p []byte) {
		b, e := seal(a, &n, p)
		if e != nil {
			t.Fatal(e)
		}
		wire = append(wire, b...)
	}
	if s.m.v2022 {
		v := append([]byte(nil), address...)
		v = binary.BigEndian.AppendUint16(v, uint16(padding))
		v = append(v, make([]byte, padding)...)
		v = append(v, initial...)
		f := []byte{0}
		f = binary.BigEndian.AppendUint64(f, stamp)
		f = binary.BigEndian.AppendUint16(f, uint16(len(v)))
		add(f)
		add(v)
	} else {
		initial = append(address, initial...)
		add(binary.BigEndian.AppendUint16(nil, uint16(len(initial))))
		add(initial)
	}
	for len(tail) > 0 {
		size := min(len(tail), MaxChunk2017)
		if s.m.v2022 {
			size = min(len(tail), MaxChunk2022)
		}
		add(binary.BigEndian.AppendUint16(nil, uint16(size)))
		add(tail[:size])
		tail = tail[size:]
	}
	return wire
}
func udpRequest(t *testing.T, s *Server, id, packet, stamp uint64, target Address, payload []byte) []byte {
	t.Helper()
	address, e := target.MarshalBinary()
	if e != nil {
		t.Fatal(e)
	}
	if !s.m.v2022 {
		salt := seq(int(packet), s.m.keySize)
		a, e := s.aead(salt)
		if e != nil {
			t.Fatal(e)
		}
		return append(salt, a.Seal(nil, make([]byte, 12), append(address, payload...), nil)...)
	}
	h := binary.BigEndian.AppendUint64(nil, id)
	h = binary.BigEndian.AppendUint64(h, packet)
	body := []byte{0}
	body = binary.BigEndian.AppendUint64(body, stamp)
	body = append(body, 0, 0)
	body = append(body, address...)
	body = append(body, payload...)
	if s.m.chacha {
		nonce := seq(int(packet), 24)
		a, _ := chacha20poly1305.NewX(s.key)
		return append(nonce, a.Seal(nil, nonce, append(h, body...), nil)...)
	}
	block, _ := aes.NewCipher(s.key)
	wire := make([]byte, 16)
	block.Encrypt(wire, h)
	a, e := s.aead(h[:8])
	if e != nil {
		t.Fatal(e)
	}
	return append(wire, a.Seal(nil, h[4:], body, nil)...)
}
func responsePlain(t *testing.T, s *Server, wire, requestSalt []byte) ([]byte, []int) {
	t.Helper()
	if len(wire) < s.m.keySize {
		t.Fatal("no salt")
	}
	a, e := s.aead(wire[:s.m.keySize])
	if e != nil {
		t.Fatal(e)
	}
	wire = wire[s.m.keySize:]
	var n counter
	var plain []byte
	var sizes []int
	take := func(size int) []byte {
		if len(wire) < size {
			t.Fatal("truncated response")
		}
		p, e := open(a, &n, wire[:size])
		if e != nil {
			t.Fatal(e)
		}
		wire = wire[size:]
		return p
	}
	if s.m.v2022 {
		h := take(1 + 8 + len(requestSalt) + 2 + 16)
		if h[0] != 1 || !bytes.Equal(h[9:9+len(requestSalt)], requestSalt) {
			t.Fatal("wrong response binding")
		}
		size := int(binary.BigEndian.Uint16(h[len(h)-2:]))
		sizes = append(sizes, size)
		plain = append(plain, take(size+16)...)
	}
	for len(wire) > 0 {
		l := take(18)
		size := int(binary.BigEndian.Uint16(l))
		sizes = append(sizes, size)
		plain = append(plain, take(size+16)...)
	}
	return plain, sizes
}
func TestConfigAndAddress(t *testing.T) {
	if _, e := NewServer(Config{Method: "none"}); !errors.Is(e, ErrMethod) {
		t.Fatal(e)
	}
	for _, name := range methods {
		m, _ := lookup(name)
		for _, size := range []int{0, m.keySize - 1, m.keySize + 1} {
			if _, e := NewServer(Config{Method: name, Key: make([]byte, size)}); !errors.Is(e, ErrKey) {
				t.Fatal(name, size, e)
			}
		}
		if _, e := NewServer(Config{Method: name, Key: make([]byte, m.keySize), MaxUDPSessions: -1}); !errors.Is(e, ErrCapacity) {
			t.Fatal(e)
		}
		k := seq(0, m.keySize)
		s, _ := NewServer(Config{Method: name, Key: k})
		k[0] = 9
		if s.key[0] == 9 {
			t.Fatal("key alias")
		}
		if m.v2022 {
			b64 := base64.StdEncoding.EncodeToString(seq(0, m.keySize))
			if _, e := KeyFromBase64(name, b64); e != nil {
				t.Fatal(e)
			}
			if _, e := KeyFromBase64(name, b64+":"+b64); !errors.Is(e, ErrKey) {
				t.Fatal("EIH accepted")
			}
			if _, e := PasswordKey2017(name, "pw"); e == nil {
				t.Fatal("password accepted for2022")
			}
		}
	}
	for _, a := range []Address{{"127.0.0.1", 0}, {"::1", 65535}, {"x", 53}, {strings.Repeat("a", 255), 443}} {
		b, e := a.MarshalBinary()
		if e != nil {
			t.Fatal(e)
		}
		got, n, e := ParseAddress(append(b, 9))
		if e != nil || got != a || n != len(b) {
			t.Fatal(got, n, e)
		}
		for i := 0; i < len(b); i++ {
			if _, _, e := ParseAddress(b[:i]); e == nil {
				t.Fatal("accepted truncated address", i)
			}
		}
	}
	for _, a := range []Address{{"", 0}, {strings.Repeat("a", 256), 1}, {"x\x00y", 1}, {"fe80::1%eth0", 1}} {
		if _, e := a.MarshalBinary(); e == nil {
			t.Fatal(a)
		}
	}
	if _, _, e := ParseAddress([]byte{2}); e == nil {
		t.Fatal("bad atyp")
	}
	// OpenSSL-compatible historical MD5 expansion known password fixture.
	k, e := PasswordKey2017(AES256GCM, "password")
	if e != nil || hex.EncodeToString(k) != "5f4dcc3b5aa765d61d8327deb882cf992b95990a9151374abd8ff8c5a7a0fe08" {
		t.Fatalf("%x %v", k, e)
	}
}
func TestTCPFragmentationLargePayloadAndServerFirst(t *testing.T) {
	for _, name := range methods {
		t.Run(name, func(t *testing.T) {
			s := server(t, name)
			salt := seq(0x20, s.m.keySize)
			tail := bytes.Repeat([]byte("payload!"), 50000)
			wire := tcpRequest(t, s, salt, uint64(testTime.Unix()), testTarget, 3, []byte("first"), tail)
			first := 0
			if s.m.v2022 {
				first = s.m.keySize + 27
			}
			tr := &memTransport{input: &slicedReader{r: bytes.NewReader(wire), first: first, step: 1}}
			c, e := s.Accept(tr)
			if e != nil {
				t.Fatal(e)
			}
			got, e := io.ReadAll(c)
			if e != nil || !bytes.Equal(got, append([]byte("first"), tail...)) {
				t.Fatal(len(got), e)
			}
			if _, e = c.Write(tail); e != nil {
				t.Fatal(e)
			}
			plain, sizes := responsePlain(t, s, tr.output.Bytes(), salt)
			if !bytes.Equal(plain, tail) {
				t.Fatal("large response corrupted")
			}
			limit := MaxChunk2017
			if s.m.v2022 {
				limit = MaxChunk2022
			}
			if sizes[0] != limit {
				t.Fatal(sizes)
			}
			for _, n := range sizes {
				if n > limit {
					t.Fatal(sizes)
				}
			}
			if e = c.CloseWrite(); !errors.Is(e, ErrHalfCloseUnsupported) {
				t.Fatal(e)
			}
			if tr.closed {
				t.Fatal("unsupported half-close closed transport")
			}
			// No application bytes are supplied; Accept must not read a later record.
			q := server(t, name)
			req := tcpRequest(t, q, seq(0x21, q.m.keySize), uint64(testTime.Unix()), Address{"x", 80}, 1, nil, nil)
			f := &memTransport{input: bytes.NewReader(req)}
			cc, e := q.Accept(f)
			if e != nil {
				t.Fatal("server-first header", e)
			}
			if _, e = cc.Write([]byte("welcome")); e != nil {
				t.Fatal(e)
			}
		})
	}
}
func TestTCPValidationAndReplay(t *testing.T) {
	for _, name := range methods {
		t.Run(name, func(t *testing.T) {
			s := server(t, name)
			salt := seq(0x20, s.m.keySize)
			valid := tcpRequest(t, s, salt, uint64(testTime.Unix()), testTarget, 1, []byte("initial"), nil)
			bad := bytes.Clone(valid)
			bad[len(bad)-1] ^= 1
			if _, e := s.Accept(&memTransport{input: bytes.NewReader(bad)}); !errors.Is(e, ErrAuth) {
				t.Fatal(e)
			}
			if st := s.Stats(); st.TCPSalts+st.Salts2017 != 0 {
				t.Fatal("bad tag committed", st)
			}
			c, e := s.Accept(&memTransport{input: bytes.NewReader(valid)})
			if e != nil {
				t.Fatal(e)
			}
			if _, e = s.Accept(&memTransport{input: bytes.NewReader(valid)}); !errors.Is(e, ErrReplay) {
				t.Fatal("duplicate salt", e)
			}
			// Wrong payload nonce/tag in a later frame poisons the reader.
			tail := []byte("tail")
			a, _ := s.aead(salt)
			var n counter
			n.value[0] = 2
			length, _ := seal(a, &n, []byte{0, byte(len(tail))})
			wrongNonce := counter{}
			encrypted, _ := seal(a, &wrongNonce, tail)
			c.reader.r = bytes.NewReader(append(length, encrypted...))
			if _, e = io.ReadAll(c); !errors.Is(e, ErrAuth) {
				t.Fatal("wrong nonce accepted", e)
			}
			if _, e = c.Read(make([]byte, 1)); !errors.Is(e, ErrAuth) {
				t.Fatal("reader not poisoned", e)
			}
			for _, cut := range []int{0, 1, s.m.keySize - 1, len(valid) - 1} {
				q := server(t, name)
				if _, e = q.Accept(&memTransport{input: bytes.NewReader(valid[:cut])}); e == nil {
					t.Fatal("accepted truncated request", cut)
				}
			}
			if s.m.v2022 {
				short := &memTransport{input: &slicedReader{r: bytes.NewReader(valid), step: 1}}
				if _, e = server(t, name).Accept(short); !errors.Is(e, ErrInitialRead) {
					t.Fatal("SIP022 initial-read policy", e)
				}
				if short.closed {
					t.Fatal("implicit observable close")
				}
				for _, offset := range []int64{-31, 31} {
					wire := tcpRequest(t, s, seq(0x21, s.m.keySize), uint64(testTime.Unix()+offset), testTarget, 1, nil, nil)
					if _, e = server(t, name).Accept(&memTransport{input: bytes.NewReader(wire)}); !errors.Is(e, ErrTimestamp) {
						t.Fatal(offset, e)
					}
				}
				for _, pad := range []int{0, 901} {
					wire := tcpRequest(t, s, seq(0x22, s.m.keySize), uint64(testTime.Unix()), testTarget, pad, nil, nil)
					if _, e = server(t, name).Accept(&memTransport{input: bytes.NewReader(wire)}); !errors.Is(e, ErrFormat) {
						t.Fatal("padding rule", pad, e)
					}
				}
				// A server-direction fixed header cannot authenticate as a request.
				f := &memTransport{input: bytes.NewReader(valid)}
				cc, e := server(t, name).Accept(f)
				if e != nil {
					t.Fatal(e)
				}
				cc.Write([]byte("reply"))
				if _, e = server(t, name).Accept(&memTransport{input: bytes.NewReader(f.output.Bytes())}); e == nil {
					t.Fatal("response reflected as request")
				}
			}
		})
	}
}

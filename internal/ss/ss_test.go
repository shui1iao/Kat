func seq(start, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = byte(start + i)
	}
	return b
}
func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b, e := hex.DecodeString(s)
	if e != nil {
		t.Fatal(e)
	}
	return b
}
func server(t *testing.T, name string) *Server {
	t.Helper()
	m, e := lookup(name)
	if e != nil {
		t.Fatal(e)
	}
	s, e := NewServer(Config{Method: name, Key: seq(0, m.keySize), UserID: "alice"})
	if e != nil {
		t.Fatal(e)
	}
	s.now = func() time.Time { return testTime }
	return s
}

type memTransport struct {
	input  io.Reader
	output bytes.Buffer
	writes int
	closed bool
}

func (m *memTransport) Read(p []byte) (int, error)  { return m.input.Read(p) }
func (m *memTransport) Write(p []byte) (int, error) { m.writes++; return m.output.Write(p) }
func (m *memTransport) Close() error                { m.closed = true; return nil }

type slicedReader struct {
	r           io.Reader
	first, step int
	done        bool
}

func (r *slicedReader) Read(p []byte) (int, error) {
	limit := r.step
	if !r.done && r.first > 0 {
		limit = r.first
		r.done = true
	}
	if limit > 0 && len(p) > limit {
		p = p[:limit]
	}
	return r.r.Read(p)
}

